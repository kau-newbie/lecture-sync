// Writes references/INDEX.md: for each reference file, every "## " section with its
// 1-based line range, so a reader can use Read with offset and limit.
// Usage: node scripts/ref-index.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "references");
const files = readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "INDEX.md").sort();
const out = [
  "# Reference index",
  "",
  "Read a section with `Read` using `offset` = start line and `limit` = lines. Generated by `node scripts/ref-index.mjs`; do not edit by hand.",
  "",
];
for (const f of files) {
  const lines = readFileSync(join(dir, f), "utf8").split("\n");
  if (lines[lines.length - 1] === "") lines.pop();
  const heads = [];
  let inCode = false;
  lines.forEach((l, i) => {
    if (l.startsWith("```")) inCode = !inCode;
    if (!inCode && /^#{1,2} /.test(l)) heads.push({ i: i + 1, t: l.replace(/^#+ /, "") });
  });
  out.push(`## ${f} (${lines.length} lines)`, "");
  heads.forEach((h, k) => {
    const end = k + 1 < heads.length ? heads[k + 1].i - 1 : lines.length;
    if (h.i === 1) return; // file title line
    out.push(`- ${h.t}: lines ${h.i}-${end} (${end - h.i + 1})`);
  });
  out.push("");
}
writeFileSync(join(dir, "INDEX.md"), out.join("\n"));
console.log(`wrote references/INDEX.md for ${files.length} files`);
